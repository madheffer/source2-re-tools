"""address_doc.py [out.md] -- docs/ADDRESSES.md and docs/addresses/ from the hand-kept name lists.

Every address the port relies on lives in tools/re/names/make_manual.py, one
list per DLL build, each address tagged with the module it was decompiled for
(`s2c:baked/lighting`, `s2c:entities/lump`, ...). This writes one page per
module, docs/addresses/<module>.md (s2c:baked/lighting -> addresses/baked/lighting.md),
holding that module's addresses per DLL build and where src/ cites each one,
and docs/ADDRESSES.md as the index: every module's page and every build's
identity (size, SHA-256, PE timestamp, whether the installed game still has it).
Rerun after editing make_manual.py (and after make_manual.py itself has been run).
"""
import datetime
import glob
import hashlib
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
NAMES = os.path.join(HERE, "names")
CS2 = os.environ.get("CS2_DIR", r"D:\Steam\steamapps\common\Counter-Strike Global Offensive")
INSTALLED = {"hammer": os.path.join(CS2, "game", "bin", "win64", "tools", "hammer.dll")}
INSTALLED.update({d: os.path.join(CS2, "game", "csgo", "bin", "win64", d + ".dll") for d in ("client", "server", "modtools")})
sys.path.insert(0, HERE)
import paths  # noqa: E402
BUILDS = [paths.BINARIES, paths.STAGING]
GENERATED = "<!-- generated by tools/re/address_doc.py from tools/re/names/make_manual.py; edit that, not this -->"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def pe_time(path):
    with open(path, "rb") as f:
        head = f.read(4096)
    pe = struct.unpack_from("<I", head, 0x3C)[0]
    stamp = struct.unpack_from("<I", head, pe + 8)[0]
    return datetime.datetime.fromtimestamp(stamp, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def build_file(dll, build):
    for d in BUILDS:
        p = os.path.join(d, f"{dll}_{build}.dll")
        if os.path.exists(p):
            return p
    installed = INSTALLED.get(dll, os.path.join(CS2, "game", "bin", "win64", dll + ".dll"))
    return installed if os.path.exists(installed) else None


def patch_verdicts():
    """Per DLL, the tracked-address line of the newest patch_check report."""
    reports = sorted(glob.glob(os.path.join(paths.PATCH_REPORTS, "*.md")), key=os.path.getmtime)
    if not reports:
        return None, {}
    verdicts, dll = {}, None
    for line in open(reports[-1], encoding="utf-8"):
        m = re.match(r"- (\w+): installed build is", line)
        if m:
            dll = m.group(1)
        elif dll and "tracked addresses" in line:
            verdicts[dll] = line.strip(" -\n")
            dll = None
    return os.path.basename(reports[-1]), verdicts


def citations():
    """Every src/ line that names an address, keyed by the address."""
    found = {}
    pattern = re.compile(r"(?:FUN_|0x)?(1[0-9a-f]{8})\b", re.I)
    for path in glob.glob(os.path.join(REPO, "src", "**", "*.cs"), recursive=True):
        rel = os.path.relpath(path, REPO).replace("\\", "/")
        if "/bin/" in rel or "/obj/" in rel:
            continue
        with open(path, encoding="utf-8", errors="replace") as f:
            for n, line in enumerate(f, 1):
                for m in pattern.finditer(line):
                    found.setdefault(m.group(1).lower(), []).append(f"{rel}:{n}")
    return found


def module_page(module):
    """s2c:baked/lighting -> baked/lighting.md; an untagged address -> untagged.md."""
    tag = module.split(":", 1)[1] if module.startswith("s2c:") else module
    tag = re.sub(r"[^A-Za-z0-9/_-]+", "-", tag).strip("-/")
    return (tag or "untagged") + ".md"


def table(rows, cited):
    out = ["| address | name | what | cited in |", "|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: int(r["addr"], 16)):
        where = cited.get(r["addr"].lower(), [])
        shown = ", ".join(f"`{w}`" for w in where[:3]) + (f" +{len(where) - 3}" if len(where) > 3 else "")
        note = (r.get("note") or "").replace("|", "\\|")
        out.append(f"| `{r['addr']}` | `{r['name']}` | {note} | {shown} |")
    return out


def by_build(entries):
    return sorted(entries, key=lambda t: (t[0], t[1]))


def main(out):
    cited = citations()
    report, verdicts = patch_verdicts()
    lists = sorted(glob.glob(os.path.join(NAMES, "*.manual.json")))
    pages_dir = os.path.join(os.path.dirname(os.path.abspath(out)), "addresses")

    builds = []   # (dll, build, identity cells, address count)
    modules = {}  # module -> [(dll, build, rows)]
    total = 0
    for path in lists:
        stem = os.path.basename(path)[: -len(".manual.json")]
        dll, build = stem.rsplit("_", 1)
        rows = json.load(open(path, encoding="utf-8"))["functions"]
        total += len(rows)
        source = build_file(dll, build)
        if source:
            digest = sha256(source)
            installed = INSTALLED.get(dll, os.path.join(CS2, "game", "bin", "win64", dll + ".dll"))
            same = os.path.exists(installed) and sha256(installed) == digest
            cells = [f"`{os.path.basename(source)}`", f"{os.path.getsize(source):,}", pe_time(source),
                     f"`{digest}`", "this build" if same else "a different build", verdicts.get(dll, "")]
        else:
            cells = ["not found locally", "", "", "", "", ""]
        builds.append((dll, build, cells, len(rows)))
        grouped = {}
        for r in rows:
            grouped.setdefault(r.get("module") or "(untagged)", []).append(r)
        for module, mrows in grouped.items():
            modules.setdefault(module, []).append((dll, build, mrows))

    # One page per module. A page an earlier run wrote for a module that has no addresses now is removed.
    written = set()
    for module in sorted(modules):
        page = module_page(module)
        up = "../" * page.count("/")  # from docs/addresses/<page> back to docs/addresses/
        target = os.path.join(pages_dir, *page.split("/"))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        count = sum(len(rows) for _, _, rows in modules[module])
        lines = [
            GENERATED,
            "",
            f"# Addresses: {module}",
            "",
            f"The {count} addresses decompiled for `{module}`, per DLL build, with where src/ cites each one.",
            f"Each build's file, SHA-256 and whether the installed game still ships it: [ADDRESSES.md]({up}../ADDRESSES.md).",
            "",
        ]
        for dll, build, rows in by_build(modules[module]):
            lines += [f"## {dll}.dll, build {build}", "", f"{len(rows)} addresses.", ""]
            lines += table(rows, cited)
            lines.append("")
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
        written.add(os.path.normcase(os.path.abspath(target)))
    for old in glob.glob(os.path.join(pages_dir, "**", "*.md"), recursive=True):
        if os.path.normcase(os.path.abspath(old)) in written:
            continue
        with open(old, encoding="utf-8") as f:
            if f.readline().strip() == GENERATED:
                os.remove(old)

    lines = [
        GENERATED,
        "",
        "# Addresses",
        "",
        "Every function and data address the port relies on, per module and DLL build.",
        "Generated by `tools/re/address_doc.py` from `tools/re/names/make_manual.py`,",
        "which is the one place addresses are kept: add them there, run it, then run",
        "this. `tools/re/apply_names.py` writes the names into the Ghidra project,",
        "and `tools/re/patch_check.py` finds every one again after a CS2 update",
        "(identical, relocated, moved, changed or missing), so this list is how a",
        "port is kept honest across patches.",
        "",
        "Every address is tagged with the module it was decompiled for, and every module",
        "has its own page under [addresses/](addresses/): its addresses per DLL build and",
        "where src/ cites them.",
        "",
        "All the DLLs load at 0x180000000, so an address means nothing without its",
        "build: the build table names the file each list was read from. \"Installed\"",
        "says whether the game on this machine still ships that exact build.",
        "",
        "Names are ours unless they carry a class (`CMapCable::vf217` is an RTTI",
        "slot, `CVoxelSampler3::MergeClusterSet` an assert string). The harvested",
        "names (asserts, RTTI, log strings; tens of thousands per DLL) are in",
        "`tools/re/names/<dll>_<build>.json`, not here.",
        "",
        f"{total} addresses over {len(lists)} builds and {len(modules)} modules.",
        "",
        "## Modules",
        "",
        "| module | page | addresses | builds |",
        "|---|---|---|---|",
    ]
    for module in sorted(modules):
        page = module_page(module)
        count = sum(len(rows) for _, _, rows in modules[module])
        used = ", ".join(f"{dll} {build}" for dll, build, _ in by_build(modules[module]))
        lines.append(f"| `{module}` | [{page[:-3]}](addresses/{page}) | {count} | {used} |")
    lines += [
        "",
        "## Builds",
        "",
        f"The last column but one is the newest patch_check report ({report or 'none found'}).",
        "",
        "| DLL | build | file | bytes | PE time | SHA-256 | installed | against the installed build | addresses |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for dll, build, cells, count in builds:
        lines.append(f"| {dll}.dll | {build} | " + " | ".join(cells) + f" | {count} |")
    lines.append("")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{total} addresses over {len(lists)} builds -> {out} and {len(modules)} module pages in {pages_dir}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "docs", "ADDRESSES.md"))
